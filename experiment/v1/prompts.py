"""Подсказки для двух вариантов с моделью. Одна и та же модель используется и как
«простая LLM», которая пишет сводку целиком, и как извлекатель фактов для СОВЫ.
Правила предметной области в подсказке простой LLM те же, что в профиле ядра:
сравнение честное, вопрос в том, справится ли модель, если ей просто объяснить
правила словами.
"""
from __future__ import annotations

ATTRS = {
    "distance_km": "расстояние от кромки пожара до посёлка, км",
    "area_ha": "площадь пожара, га",
    "wind": "ветер: румб (С, СВ, В, ЮВ, Ю, ЮЗ, З, СЗ) и скорость, м/с, например \"СЗ 10\"",
    "road": "дорога на райцентр: \"открыта\" или \"закрыта\"",
    "people_in_zone": "население в зоне ЧС, человек",
    "evacuated": "эвакуировано, человек",
    "personnel": "личный состав на тушении, человек",
    "equipment": "техника, единиц",
    "casualties": "пострадавшие, человек (\"пострадавших нет\" = 0)",
}

RULES = """Правила штаба.
1. Время местное, Якутск, МСК+6. Если в донесении время по Москве (МСК), прибавь 6 часов.
2. Важно время наблюдения, а не время получения. Донесение, которое пришло позже, но описывает более раннее время, не заменяет более свежее наблюдение.
3. Срок годности сведений: расстояние, площадь, ветер, эвакуированные 2 часа; дорога, население, личный состав, техника 3 часа; пострадавшие 4 часа. Старше срока = «устарел».
4. Допуски. Расстояние: два значения совместимы, если различаются не больше чем на 0,8 км (или 20%) плюс 1,2 км на каждый час между наблюдениями (кромка не движется быстрее 1,2 км/ч). Площадь: 40 га (или 25%) плюс 180 га в час.
5. Пересказ чужих сведений («по данным главы», «глава сообщил») не второй источник и ничего не подтверждает.
6. Если время наблюдения не указано, не выдумывай его. Считай, что наблюдение было не раньше чем за час до получения. Такое донесение ничего не подтверждает, а у источника надо запросить время.
7. Статусы показателя: «подтверждён» (два независимых источника почти одновременно, в пределах 30 минут, согласны), «не подтверждён» (есть свежие сведения, но от одного источника), «оспорен» (независимые источники противоречат друг другу, или новое значение не сходится с прежним с учётом допусков и скорости), «устарел», «нет сведений». Нормальное изменение обстановки во времени не противоречие.
8. План действий (условный): эвакуация посёлка нужна, если кромка ближе 3 км. Решение по эвакуации: «нужна», «не нужна» или «уточнить» (если сведения спорные, устарели или с учётом скорости кромка уже могла пройти порог). Вывоз по дороге на райцентр: «можно», «нельзя» (дорога закрыта) или «уточнить» (сведения спорные или устарели)."""

SCHEMA_BASELINE = """{
  "indicators": {"<код показателя>": {"value": "<значение строкой или null>", "status": "<статус>", "sources": ["<номера донесений, на которых основано значение>"]}},
  "decisions": {"evacuation": "нужна | не нужна | уточнить", "road": "можно | нельзя | уточнить"},
  "asks": [{"attr": "<код показателя>", "kind": "value | time", "rid": "<номер донесения, если запрашиваешь время, иначе null>"}]
}"""


def attrs_text() -> str:
    return "\n".join(f"- {k}: {v}" for k, v in ATTRS.items())


def baseline_prompt(case: dict, reports: list[dict]) -> str:
    lines = "\n".join(f"{r['id']}, получено {r['received']}, {r['source']}: {r['text']}" for r in reports)
    return (f"Ты помогаешь офицеру штаба ликвидации ЧС подготовить черновик сводки. Ландшафтный пожар у п. Кедровый.\n"
            f"Ниже все донесения, которые штаб получил к {case['T']}. Составь сводку на {case['T']}.\n\n"
            f"{RULES}\n\nПоказатели (коды):\n{attrs_text()}\n\nДонесения:\n{lines}\n\n"
            f"Ответь только JSON по схеме, без пояснений. Укажи все девять показателей.\n{SCHEMA_BASELINE}")


EXTRACT_SCHEMA = """{"facts": [{"attr": "<код показателя>", "value": "<значение строкой>"}],
 "time": "<ЧЧ:ММ как написано в тексте или null, если времени нет>",
 "msk": <true, если время указано по Москве>,
 "relay_from": "<если донесение пересказывает чужие сведения: кто наблюдал на самом деле, одно из: РТП, Глава поселения, ЕДДС, ИСДМ, Авиалесоохрана, Метеостанция, БПЛА, ГИБДД; иначе null>"}"""


def extract_prompt(report: dict) -> str:
    return (f"Извлеки факты из донесения в штаб ЛЧС. Не добавляй того, чего нет в тексте.\n"
            f"Показатели (коды):\n{attrs_text()}\n\n"
            f"Донесение от источника «{report['source']}»: {report['text']}\n\n"
            f"Ответь только JSON по схеме:\n{EXTRACT_SCHEMA}")
