"""Подсказки v2. Одна и та же облачная модель работает в двух ролях: как «простая LLM»,
которая получает все донесения и правила словами и пишет сводку целиком, и как
извлекатель утверждений для СОВЫ. Текст правил один для всех вариантов и описывает
то же, что делает код ядра. На четырёх-десяти донесениях простой RAG с поиском
равен подаче всех донесений в контекст, поэтому отдельно он здесь не запускается.
"""
from __future__ import annotations

ATTRS = {
    "distance_km": "расстояние от пожара до посёлка, км",
    "area_ha": "площадь пожара, га",
    "road": "дорога (трасса) на райцентр: \"открыта\" или \"закрыта\"",
    "evacuated": "эвакуировано (вывезено) жителей, человек",
}
SOURCES = ["РТП", "Глава поселения", "ЕДДС", "ИСДМ", "Авиалесоохрана", "БПЛА", "ГИБДД", "Дорожная служба"]
SUBJECTS = ["кромка, посёлок", "северная кромка, посёлок", "южная кромка, посёлок"]

RULES = f"""Правила штаба (одни и те же для всех вариантов).
1. Время местное, МСК+6. Время по Москве (МСК) переводи в местное: прибавь 6 часов.
2. Время наблюдения берётся только из текста. Если в тексте нет часов и минут, время наблюдения не указано; не придумывай его. Про такое утверждение известно только, что наблюдали не позже, чем оно пришло.
3. Источник. «Передал» это отправитель донесения. Если отправитель ссылается на другого («по данным X», «со слов X», «X сообщил»), это пересказ, и «ссылается на» = X. «Наблюдал» указывай, только если в тексте прямо сказано, кто видел сам; иначе наблюдатель не указан. Если отправитель сообщает от себя, без ссылки, наблюдатель это он сам. Пересказ не второй независимый источник: он принадлежит тому, на кого ссылаются.
4. Участок для расстояния: одно из {", ".join(f"«{s}»" for s in SUBJECTS)}. Если не сказано, что расстояние до кромки (например, «огонь в 2 км»), участок не указан. Утверждения о разных участках это разные объекты, их не сравнивают.
5. Одновременными считаются наблюдения, между которыми не больше 30 минут. Допуски: расстояние max(0,8 км; 20% от среднего) плюс 0,02 км на каждую минуту между наблюдениями; площадь max(40 га; 25%) плюс 3 га в минуту; эвакуированные max(20 чел.; 20%) плюс 3 чел. в минуту; дорога без допуска, её состояние может меняться в любую сторону, это изменение, а не скачок. В пределах допуска значения совместимы.
6. Текущие сведения по показателю: утверждения с известным временем, не дальше 30 минут от самого позднего наблюдения. Утверждение без времени сравнивается с текущими, только если пришло не раньше чем за 30 минут до самого позднего наблюдения; иначе это история.
7. Статус показателя, первый подходящий по порядку:
   «нет сведений»: утверждений нет;
   «устарел»: последнее наблюдение старше срока (расстояние, площадь, эвакуированные 120 минут, дорога 180 минут);
   «противоречие»: два текущих утверждения от независимых источников, у обоих известно время и наблюдатель, участок один и тот же (для расстояния он указан у обоих), значения несовместимы;
   «требует уточнения»: значения несовместимы, если считать их одновременными, но сопоставить их нельзя, потому что у одного не указано время, участок или наблюдатель; или новое значение источника несовместимо с его же прежним замером при допустимой скорости изменения и никем не подтверждено;
   «подтверждён»: два текущих утверждения от независимых источников, у обоих известно время и наблюдатель, участок один, значения совместимы;
   «не подтверждён»: всё остальное (по сути один источник).
   Изменение обстановки во времени (разные моменты, совместимые значения) не противоречие.
8. Правила учебного сценария, это не рекомендации: эвакуация, если до кромки 3 км и меньше; вывоз по дороге на райцентр, если она открыта. Результат для эвакуации: «порог достигнут», «порог не достигнут» или «нельзя определить до уточнения»; для дороги: «дорога закрыта», «дорога открыта» или «нельзя определить до уточнения». «Нельзя определить», если текущие значения (вместе со сравнимыми с ними утверждениями без времени) лежат по разные стороны порога, или сведений нет, или они устарели. Входные данные правила ненадёжны, если статус показателя «противоречие», «требует уточнения», «устарел» или «нет сведений», или результат «нельзя определить».
9. Вопросы: по показателю со статусом «противоречие», «требует уточнения», «устарел» или «нет сведений» подготовь вопрос. Кому: при противоречии обоим источникам; при «требует уточнения» тому, чьё утверждение неполное, а при пересказе тому, на кого ссылаются; при резком расхождении с прежним замером тому же источнику. Что уточнить: время, участок, кто наблюдал, значение."""

SCHEMA_SUMMARY = """{
  "indicators": {"<код>": {"value": "<текущее значение строкой; если есть спор, обе стороны>", "status": "<статус>",
                            "basis": [{"rid": "<номер донесения>", "value": "<что в нём сказано>", "quote": "<точная цитата из текста>"}]}},
  "rules": {"evacuation": {"result": "<результат>", "inputs_reliable": true},
            "road": {"result": "<результат>", "inputs_reliable": true}},
  "questions": [{"attr": "<код>", "to": "<кому>", "text": "<текст вопроса>"}]
}"""

SCHEMA_EXTRACT = """{"claims": [{"attr": "<код>", "value": "<значение строкой>", "time": "<ЧЧ:ММ местного времени или null>",
             "cited": "<на кого ссылается или null>", "observer": "<кто наблюдал, только если сказано явно, или null>",
             "subject": "<участок для расстояния или пустая строка>", "quote": "<точный фрагмент текста со значением>"}]}"""


def attrs_text() -> str:
    return "\n".join(f"- {k}: {v}" for k, v in ATTRS.items())


def summary_prompt(case: dict, reports: list[dict]) -> str:
    lines = "\n".join(f"{r['id']}, получено {r['received']}, передал {r['source']}: {r['text']}" for r in reports)
    return (f"Ты помогаешь офицеру штаба ликвидации ЧС подготовить черновик сводки. Ландшафтный пожар у посёлка.\n"
            f"Ниже все донесения, которые штаб получил к {case['T']}. Составь сводку на {case['T']}.\n\n"
            f"{RULES}\n\nПоказатели (коды):\n{attrs_text()}\n\nИсточники: {', '.join(SOURCES)}.\n\n"
            f"Донесения:\n{lines}\n\n"
            f"Ответь только JSON по схеме, без пояснений. Укажи все четыре показателя.\n{SCHEMA_SUMMARY}")


def extract_prompt(report: dict) -> str:
    return (f"Извлеки утверждения из донесения в штаб ЛЧС. Не добавляй того, чего нет в тексте. "
            f"Пункты 1–4 правил ниже говорят, как заполнять время, источник и участок.\n\n"
            f"{RULES.split('5.')[0].strip()}\n\nПоказатели (коды):\n{attrs_text()}\n\n"
            f"Источники (для полей cited и observer): {', '.join(SOURCES)}.\n\n"
            f"Донесение получено в {report['received']}, передал {report['source']}: {report['text']}\n\n"
            f"Ответь только JSON по схеме:\n{SCHEMA_EXTRACT}")
